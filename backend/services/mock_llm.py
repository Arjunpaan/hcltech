def _file_blocks(files: dict[str, str], reasons: dict[str, str] | None = None) -> str:
    """Format files the same way the real AI is asked to (### FILE / ### END FILE)."""
    parts = []
    for path, content in files.items():
        parts.append(f"### FILE: {path}")
        if reasons and path in reasons:
            parts.append(f"### REASON: {reasons[path]}")
        parts.append(content.rstrip("\n"))
        parts.append("### END FILE")
    return "\n".join(parts) + "\n"


def respond(agent: str, system_prompt: str, user_prompt: str) -> str:
    """Return a canned answer for the given agent."""
    if agent == "analyst":
        return json.dumps(ANALYSIS)
    if agent == "designer":
        return json.dumps(DESIGN)
    if agent == "developer":
        return _file_blocks({"app/main.py": MAIN_V1, "app/models.py": MODELS_V1, "app/storage.py": STORAGE_PY})
    if agent == "tester":
        return _file_blocks({"tests/test_contact.py": TESTS_PY})
    if agent == "reviewer":
        return json.dumps(REVIEW_WITH_DEFECTS if "ADMIN_TOKEN" in user_prompt else REVIEW_CLEAN)
    if agent == "security":
        return json.dumps(SECURITY_WITH_DEFECTS if "ADMIN_TOKEN" in user_prompt else SECURITY_CLEAN)
    if agent == "fixer":
        return _file_blocks(
            {"app/main.py": MAIN_FIXED, "app/models.py": MODELS_FIXED},
            {"app/main.py": "Removed the hard-coded token (secret scan + security finding).",
             "app/models.py": "Added phone pattern and address length limit (failing test AC-03)."},
        )
    if agent == "release":
        match = re.search(r"DECISION:\s*([A-Z ]+)", user_prompt)
        decision = match.group(1).strip() if match else "UNKNOWN"
        return (f"Recommendation: {decision}. This follows the gate results computed by the platform. "
                "Tests, quality and security checks were executed by real tools; see the gate table and "
                "traceability matrix for the evidence. The generated code is not production-ready "
                "until a human engineer reviews it.")
    return "{}"
