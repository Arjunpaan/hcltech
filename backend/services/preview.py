"""
services/preview.py - Show and run the code the agents built.

1. code_page(run_id)  -> a simple HTML page with every final file (opens in a browser tab).
2. launch(run_id)     -> starts the GENERATED app with uvicorn on its own port
                         (9000 + run id) so you can try it live at http://localhost:<port>/docs
3. stop(run_id)       -> stops that app.

Safety: the generated app runs only on 127.0.0.1 (this computer only), from the
run's own folder, with an environment that contains no API keys.
"""

import html
import socket
import subprocess
import sys
import time

import db
from services import workspace
from services.runner import _clean_env

# run_id -> (process, port, log file) for every generated app that is running now
_running: dict[int, tuple] = {}


def code_page(run_id: int) -> str:
    """Build an HTML page that shows every final file of the generated project."""
    run = db.get_run(run_id) or {}
    files = db.current_files(run_id)
    versions = {r["name"]: r["v"] for r in db.query(
        "SELECT name, MAX(version) AS v FROM artifacts WHERE run_id = ? AND kind = 'file' GROUP BY name", (run_id,))}
    links = "".join(f'<li><a href="#f{i}">{html.escape(p)}</a> <small>v{versions.get(p, 1)}</small></li>'
                    for i, p in enumerate(files))
    blocks = "".join(
        f'<h2 id="f{i}">{html.escape(p)} <small>v{versions.get(p, 1)}</small></h2>'
        f"<pre>{html.escape(c)}</pre>" for i, (p, c) in enumerate(files.items()))
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>Run {run_id} - final code</title>
<style>
 body {{ font-family: system-ui, sans-serif; margin: 24px; background: #f5f6f8; color: #1d2330; }}
 pre {{ background: #0f172a; color: #e2e8f0; padding: 14px; border-radius: 8px; overflow-x: auto; font-size: 13px; }}
 h2 {{ font-size: 16px; margin-top: 28px; }} small {{ color: #667085; font-weight: normal; }}
 .note {{ background: #fff8e6; border-left: 4px solid #b26a00; padding: 8px 12px; }}
</style></head><body>
<h1>Run #{run_id} - {html.escape(run.get("title") or "")}: final generated code</h1>
<p>Decision: <b>{html.escape(run.get("decision") or "pending")}</b> &middot; fix rounds used: {run.get("fix_round", 0)}</p>
<p class="note">Generated by AI agents, checked by pytest, Ruff, Bandit and a secret scan.
Not production-ready until a human engineer reviews it.</p>
<ul>{links}</ul>{blocks}</body></html>"""


def _free_port(start: int) -> int:
    """Find a free port, starting at `start`."""
    for port in range(start, start + 50):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            if sock.connect_ex(("127.0.0.1", port)) != 0:
                return port
    raise RuntimeError("No free port found")


def launch(run_id: int) -> dict:
    """Start the generated FastAPI app and return its links."""
    stop(run_id)
    folder = workspace.build(run_id)
    if not (folder / "app" / "main.py").exists():
        raise RuntimeError("This run has no app/main.py yet - wait until the Developer Agent has written code.")
    port = _free_port(9000 + run_id)
    (folder / ".reports").mkdir(exist_ok=True)
    log_path = folder / ".reports" / "preview.log"
    log_file = open(log_path, "w", encoding="utf-8")
    process = subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", str(port)],
        cwd=folder, env=_clean_env(folder), stdout=log_file, stderr=subprocess.STDOUT)
    # Wait up to 10 seconds for the app to start listening.
    for _ in range(40):
        time.sleep(0.25)
        if process.poll() is not None:
            log_file.close()
            output = log_path.read_text(encoding="utf-8", errors="ignore")
            raise RuntimeError(f"The generated app stopped while starting:\n{output[-1500:]}")
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            if sock.connect_ex(("127.0.0.1", port)) == 0:
                break
    _running[run_id] = (process, port, log_file)
    db.log_event(run_id, "PREVIEW", "system", f"Generated app started at http://localhost:{port}/docs")
    return status(run_id)


def stop(run_id: int) -> dict:
    """Stop the generated app of this run (if it is running)."""
    entry = _running.pop(run_id, None)
    if entry:
        process, port = entry[0], entry[1]
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
        entry[2].close()
        db.log_event(run_id, "PREVIEW", "system", f"Generated app on port {port} stopped")
    return status(run_id)


def status(run_id: int) -> dict:
    """Is the generated app running, and where?"""
    entry = _running.get(run_id)
    if not entry or entry[0].poll() is not None:
        _running.pop(run_id, None)
        return {"running": False}
    port = entry[1]
    return {"running": True, "port": port, "url": f"http://localhost:{port}",
            "docs_url": f"http://localhost:{port}/docs"}


def stop_all() -> None:
    """Stop every generated app (called when the backend shuts down)."""
    for run_id in list(_running):
        stop(run_id)
